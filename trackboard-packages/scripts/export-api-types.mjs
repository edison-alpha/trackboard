#!/usr/bin/env node
// Copies the wire types (api-types/src/*.ts except index.ts) into trackboard-fe/lib/api/, so the frontend builds without
// importing from outside its own folder while the backend and frontend still share one definition. Run after any
// change to api-types:
//
//   node scripts/export-api-types.mjs

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const FILES = ["types.ts", "ai.ts"];
const OUT = resolve(ROOT, "../trackboard-fe/lib/api");

mkdirSync(OUT, { recursive: true });
for (const file of FILES) {
  const header = `// Generated by trackboard-packages/scripts/export-api-types.mjs from trackboard-packages/api-types/src/${file}.
// Do not edit here: change api-types and rerun the script, so trackboard-be and trackboard-fe keep one definition.
`;
  const target = resolve(OUT, file);
  writeFileSync(target, header + readFileSync(resolve(ROOT, "api-types/src", file), "utf8"));
  console.log(`wrote ${target}`);
}
