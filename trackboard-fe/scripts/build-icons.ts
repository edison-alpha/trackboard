/*
 * Bundles every icon Trackboard uses into lib/icon-data.ts, read from the full icon sets installed locally
 * (@iconify-json/solar, @iconify-json/fluent), so any icon in those libraries can be used by name and
 * still renders offline. Only the icons actually referenced end up in the app bundle.
 *
 * Picks up:
 *   - solar("name") / fluent("regular", "filled") in components/icons.tsx
 *   - icon="solar:name" / icon="fluent:name" anywhere under app/, components/, modules/
 *
 *   bun scripts/build-icons.ts
 */
import { icons as fluentSet } from "@iconify-json/fluent";
import { icons as solarSet } from "@iconify-json/solar";
import { getIcons } from "@iconify/utils";
import { Glob } from "bun";
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const solar = new Set<string>();
const fluent = new Set<string>();

const icons = readFileSync(new URL("components/icons.tsx", root), "utf8");
for (const m of icons.matchAll(/solar\("([a-z0-9-]+)"\)/g)) solar.add(`${m[1]}-linear`).add(`${m[1]}-bold`);
for (const m of icons.matchAll(/fluent\("([a-z0-9-]+)", "([a-z0-9-]+)"\)/g)) fluent.add(m[1]!).add(m[2]!);

for (const dir of ["app", "components", "modules"]) {
  for (const file of new Glob("**/*.{ts,tsx}").scanSync(new URL(dir, root).pathname.replace(/^\/([A-Z]:)/, "$1"))) {
    const text = readFileSync(new URL(`${dir}/${file}`, root), "utf8");
    for (const m of text.matchAll(/icon="(solar|fluent):([a-z0-9-]+)"/g)) (m[1] === "solar" ? solar : fluent).add(m[2]!);
  }
}

function pick(set: typeof solarSet, names: Set<string>, prefix: string) {
  const data = getIcons(set, [...names].sort());
  const missing = [...names].filter((n) => !data?.icons[n] && !data?.aliases?.[n]);
  if (!data || missing.length) throw new Error(`Not in ${prefix}: ${missing.join(", ")}`);
  return data;
}

const out = `/* Icon data (Iconify), bundled so nothing is fetched at runtime.
   Solar: CC BY 4.0. Fluent UI System Icons: MIT.
   Generated by scripts/build-icons.ts from the installed icon sets. Do not edit by hand. */
import type { IconifyJSON } from "@iconify/react";

export const SOLAR: IconifyJSON = ${JSON.stringify(pick(solarSet, solar, "solar"))};

export const FLUENT: IconifyJSON = ${JSON.stringify(pick(fluentSet, fluent, "fluent"))};
`;
writeFileSync(new URL("lib/icon-data.ts", root), out);
console.log(`bundled ${solar.size} Solar + ${fluent.size} Fluent icons (from ${Object.keys(solarSet.icons).length} + ${Object.keys(fluentSet.icons).length} available)`);
